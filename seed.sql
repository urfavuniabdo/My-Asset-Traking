INSERT INTO depreciation_entries (asset_id, period_date, amount, book_value_after, method)
SELECT
  a.id,
  p.period_date,
  ROUND((a.purchase_cost - a.salvage_value) / (a.useful_life_years * 12.0), 2),
  ROUND(a.book_value + ((a.purchase_cost - a.salvage_value) / (a.useful_life_years * 12.0)) * p.back_months, 2),
  'StraightLine'
FROM assets a
CROSS JOIN (
  SELECT '2026-05-31' AS period_date, 3 AS back_months
  UNION ALL SELECT '2026-06-30', 2
  UNION ALL SELECT '2026-07-31', 1
  UNION ALL SELECT '2026-08-31', 0
) p
WHERE a.status NOT IN ('Disposed','Lost') AND a.purchase_date IS NOT NULL
  AND a.purchase_date IS NOT NULL
  AND a.purchase_date <= '2026-05-01';

